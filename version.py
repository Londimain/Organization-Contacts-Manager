def build_about_text():
    return f"""
{APP_NAME}
Версия: {APP_VERSION}  (сборка от {APP_BUILD_DATE})

{APP_DESCRIPTION}

ОСНОВНЫЕ ВОЗМОЖНОСТИ:
- Иерархическая структура: Ответственные лица -> Организации -> 
  Магазины -> Контакты (ЛПР и Оплата).
- Цветовое кодирование типов для быстрой навигации (Ответственные, 
  Организации, Магазины и Контакты выделены разными цветами).
- Сквозной поиск по всей базе. При очистке поиска дерево 
  возвращается в исходное состояние (сохраняются открытые папки).
- Умное управление выделением: клик правой кнопкой мыши или 
  левой кнопкой по пустому месту снимает выделение. Клик по строке 
  разворачивает/сворачивает список.
- Копирование данных с визуальным откликом (текст кратковременно 
  вспыхивает зеленым цветом при копировании).
- Экспорт в Excel: файл автоматически сохраняется на Рабочем столе 
  с автоподбором ширины столбцов и рамками.
- Умный импорт из Excel (в один столбец): программа распознает 
  иерархию по цвету заливки ячеек (желтый - отв. лица, оранжевый - 
  организации, без цвета - магазины).
- Фоновый импорт с окном загрузки (интерфейс не зависает).

НОВЫЕ ВОЗМОЖНОСТИ И СЕТЕВАЯ РАБОТА:
- Поддержка локальной и сетевой базы данных. Выбор пути осуществляется 
  через меню «Настройки».
- Индикатор текущей базы в нижней панели (Локальная / Сетевая).
- Мгновенное обновление интерфейса при добавлении, редактировании или 
  удалении записей (без полной перезагрузки дерева).
- Фоновое подключение к сетевой базе и загрузка данных (программа не 
  зависает при медленном соединении).
- Автоматическое отслеживание изменений: если коллега с другого ПК 
  изменит данные в сетевой базе, программа сама подтянет обновления 
  (с сохранением открытых папок и выделенных строк).
- Встроенная система автообновления программы (проверка version.json).

ДОПОЛНИТЕЛЬНО:
- Корзина: мягкое удаление с возможностью восстановления. Кнопки 
  управления корзиной блокируются, если она пуста.
- Валидация телефонов и дат при вводе.
- Защита от случайного запуска второй копии программы.
- Современный темный интерфейс с кастомными кнопками, 
  заголовками таблицы и полосой прокрутки.

ГОРЯЧИЕ КЛАВИШИ:
- Ctrl+F — фокус в поле поиска.
- Ctrl+C — скопировать выделенные строки для вставки в Excel.
- Enter — редактировать выбранную строку (вне форм).
- Insert — добавить элемент.
- Delete — удалить выбранный элемент.
- Enter в форме — сохранить введённые данные.
- Esc — отмена/закрытие формы.

ТЕХНИЧЕСКАЯ ИНФОРМАЦИЯ:
- Технологии: Python 3.8+, PySide6 (Qt6), SQLite3, OpenPyXL.
- База данных по умолчанию: contacts.db рядом с исполняемым файлом.
  Путь к сетевой базе задается через меню «Настройки».
- Настройки и логи — в системной папке AppData (ManagerContacts).

Разработчик: {DEVELOPER}
Организация: {ORGANIZATION}
""".strip()