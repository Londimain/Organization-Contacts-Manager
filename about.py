ABOUT_TEXT = """
Менеджер контактов организаций
Версия: 1.1

Профессиональный инструмент для управления базой данных контактов, 
организаций и торговых точек.

ОСНОВНЫЕ ВОЗМОЖНОСТИ:
- Иерархическая структура: Ответственные лица -> Организации -> 
  Магазины -> Контакты.
- Разделение контактов на ЛПР (Лица, принимающие решения) и Оплату.
- Смена типа контакта без удаления (ЛПР <-> Оплата).
- Сквозной поиск по всей базе с подсветкой совпадений 
  (ФИО, адреса, телефоны, должности, номера договоров).
- Копирование данных: двойной клик или правый клик по ячейке - 
  текст в буфер обмена.
- Экспорт в Excel: файл автоматически сохраняется на Рабочем столе 
  в папке "Экспорт контактов".
- Корзина: удаление без потери данных, восстановление и очистка.
- Валидация телефонов и дат.
- Счётчики вложенных элементов в строках.

ГОРЯЧИЕ КЛАВИШИ:
- Ctrl+F - фокус в поле поиска.
- Enter - редактировать выбранную строку (вне форм).
- Insert - добавить элемент.
- Delete - удалить выбранный элемент.
- Enter в форме - сохранить введённые данные.

ТЕХНИЧЕСКАЯ ИНФОРМАЦИЯ:
- Технологии: Python 3.8+, Kivy, SQLite3, OpenPyXL.
- База данных хранится локально в файле contacts.db рядом 
  с исполняемым файлом.
- Логи работы - в файле app.log.
- Настройки (размер окна) - в settings.json.

Разработчик: Ильенков С.М.
Организация: ОАО "Компания МогНат"
Год: 2026
"""